#!/usr/bin/env python3
"""Generate packages/db/seed.sql from the domain seed JSON."""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SEED = ROOT / "packages" / "domain" / "src" / "seed"
OUT = ROOT / "packages" / "db" / "seed.sql"


def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def j(value):
    return q(json.dumps(value, ensure_ascii=False, separators=(",", ":")))


def main() -> None:
    parties = json.loads((SEED / "parties.json").read_text())
    candidates = json.loads((SEED / "candidates.json").read_text())
    demo = json.loads((SEED / "demo-scores.json").read_text())
    departments = json.loads((SEED / "departments.json").read_text())
    results = json.loads((SEED / "results-2022-departments.json").read_text())

    lines: list[str] = []
    lines.append("-- Generated by scripts/build_seed.py. Do not edit by hand.\n")
    lines.append("PRAGMA foreign_keys = ON;\n")

    # Parties
    for party in parties:
        lines.append(
            "INSERT OR REPLACE INTO parties (id, name, short_name, color, spectrum, created_at) VALUES "
            f"({q(party['id'])}, {q(party['name'])}, {q(party['short_name'])}, {q(party['color'])}, "
            f"{q(party['spectrum'])}, {q(party['created_at'])});"
        )

    # Candidates
    for candidate in candidates:
        lines.append(
            "INSERT OR REPLACE INTO candidates "
            "(id, slug, full_name, party_id, status, declared_at, birth_year, color, avatar, avatar_credit, avatar_source, name_fr, name_en, name_zh, bio_fr, bio_en, bio_zh) VALUES "
            f"({q(candidate['id'])}, {q(candidate['slug'])}, {q(candidate['full_name'])}, {q(candidate['party_id'])}, "
            f"{q(candidate['status'])}, {q(candidate['declared_at'])}, {candidate['birth_year']}, {q(candidate['color'])}, {q(candidate.get('avatar', ''))}, "
            f"{q(candidate.get('avatar_credit'))}, {q(candidate.get('avatar_source'))}, "
            f"{q(candidate['name_fr'])}, {q(candidate['name_en'])}, {q(candidate['name_zh'])}, "
            f"{q(candidate['bio_fr'])}, {q(candidate['bio_en'])}, {q(candidate['bio_zh'])});"
        )

    # Elections
    elections = [
        ("pres-2022-t1", "presidential", 1, "2022-04-10", "national"),
        ("pres-2027-t1", "presidential", 1, "2027-04-18", "national"),
        ("pres-2027-t2", "presidential", 2, "2027-05-02", "national"),
        ("leg-2027-t1", "legislative", 1, "2027-06-13", "national"),
        ("leg-2027-t2", "legislative", 2, "2027-06-20", "national"),
    ]
    for election in elections:
        lines.append(
            "INSERT OR REPLACE INTO elections (id, type, round, election_date, scope) VALUES "
            f"({q(election[0])}, {q(election[1])}, {election[2]}, {q(election[3])}, {q(election[4])});"
        )

    # Constituencies (departments for now; 577 circonscriptions later)
    seen = set()
    for department in departments:
        code = department["code"]
        if code in seen:
            continue
        seen.add(code)
        lines.append(
            "INSERT OR REPLACE INTO constituencies (id, code, name, type, department_code, region_code, geo_version) VALUES "
            f"({q('dep-' + code)}, {q(code)}, {q(department['name'])}, 'department', {q(code)}, {q(department.get('region'))}, '2026');"
        )
    for code, department in results["departments"].items():
        if code in seen:
            continue
        seen.add(code)
        lines.append(
            "INSERT OR REPLACE INTO constituencies (id, code, name, type, department_code, region_code, geo_version) VALUES "
            f"({q('dep-' + code)}, {q(code)}, {q(department['name'])}, 'department', {q(code)}, {q(department.get('region'))}, '2026');"
        )

    # Candidacies for 2027
    for candidate in candidates:
        if candidate["status"] == "withdrawn":
            continue
        lines.append(
            "INSERT OR REPLACE INTO candidacies (id, election_id, candidate_id, constituency_id, party_id, ballot_order, status) VALUES "
            f"({q('cand-' + candidate['id'] + '-pres-2027-t1')}, 'pres-2027-t1', {q(candidate['id'])}, NULL, "
            f"{q(candidate['party_id'])}, NULL, 'active');"
        )

    # Pollsters
    pollsters = [
        ("ifop", "Ifop"),
        ("ipsos", "Ipsos"),
        ("elabe", "Elabe"),
        ("odoxa", "Odoxa"),
        ("cluster17", "Cluster17"),
        ("harris", "Harris Interactive"),
        ("opinionway", "OpinionWay"),
        ("verian", "Verian"),
        ("kantar", "Kantar"),
        ("bva", "BVA Xsight"),
    ]
    for pollster in pollsters:
        lines.append(
            "INSERT OR REPLACE INTO pollsters (id, name) VALUES "
            f"({q(pollster[0])}, {q(pollster[1])});"
        )

    # Sources (RSS/API connectors; feed URLs are best-effort and verified at runtime)
    sources = [
        ("lemonde", "Le Monde", "media", "FR", "fr", "https://www.lemonde.fr/rss/une.xml"),
        ("lefigaro", "Le Figaro", "media", "FR", "fr", "https://www.lefigaro.fr/rss/figaro_actualites.xml"),
        ("liberation", "Libération", "media", "FR", "fr", "https://www.liberation.fr/arc/outboundfeeds/rss/?outputType=xml"),
        ("lesechos", "Les Échos", "media", "FR", "fr", "https://www.lesechos.fr/rss/rss_une.xml"),
        ("leparisien", "Le Parisien", "media", "FR", "fr", "https://www.leparisien.fr/rss.xml"),
        ("nouvelobs", "L'Obs", "media", "FR", "fr", "https://www.nouvelobs.com/rss.xml"),
        ("lexpress", "L'Express", "media", "FR", "fr", "https://www.lexpress.fr/rss/alaune.xml"),
        ("lepoint", "Le Point", "media", "FR", "fr", "https://www.lepoint.fr/rss.xml"),
        ("marianne", "Marianne", "media", "FR", "fr", "https://www.marianne.net/rss.xml"),
        ("franceinfo", "franceinfo", "media", "FR", "fr", "https://www.francetvinfo.fr/titres.rss"),
        ("france24", "France 24", "media", "FR", "fr", "https://www.france24.com/fr/rss"),
        ("rfi", "RFI", "media", "FR", "fr", "https://www.rfi.fr/fr/rss"),
        ("bfmtv", "BFMTV", "media", "FR", "fr", "https://www.bfmtv.com/rss/news/"),
        ("cnews", "CNews", "media", "FR", "fr", "https://www.cnews.fr/rss.xml"),
        ("tf1info", "TF1 Info", "media", "FR", "fr", "https://www.tf1info.fr/rss/"),
        ("arte", "Arte", "media", "FR", "fr", "https://www.arte.tv/fr/rss/"),
        ("publicsenat", "Public Sénat", "media", "FR", "fr", "https://www.publicsenat.fr/rss"),
        ("lcp", "LCP", "media", "FR", "fr", "https://www.lcp.fr/rss"),
        ("europe1", "Europe 1", "media", "FR", "fr", "https://www.europe1.fr/rss.xml"),
        ("rtl", "RTL", "media", "FR", "fr", "https://www.rtl.fr/rss.xml"),
        ("rmc", "RMC", "media", "FR", "fr", "https://rmc.bfmtv.com/rss/"),
        ("ouestfrance", "Ouest-France", "media", "FR", "fr", "https://www.ouest-france.fr/rss/une"),
        ("lavoixdunord", "La Voix du Nord", "media", "FR", "fr", "https://www.lavoixdunord.fr/rss"),
        ("gdelt", "GDELT DOC 2.0", "aggregator", "US", "multi", "https://api.gdeltproject.org/api/v2/doc/doc"),
    ]
    for source in sources:
        lines.append(
            "INSERT OR REPLACE INTO sources (id, name, kind, country, lang, feed_url, active) VALUES "
            f"({q(source[0])}, {q(source[1])}, {q(source[2])}, {q(source[3])}, {q(source[4])}, {q(source[5])}, 1);"
        )

    # Demo scores
    for score in demo["candidates"]:
        components = {
            "poll": score["poll_avg"],
            "market": score["market_prob"],
            "media": score["share_of_voice"],
            "social": score["social_attention"],
            "elite": score["elite"],
            "trend": score["trend"],
            "demo": True,
        }
        lines.append(
            "INSERT OR REPLACE INTO scores (id, entity_id, entity_type, as_of, poll_avg, market_prob, share_of_voice, social_attention, stance_balance, composite, components_json, confidence) VALUES "
            f"({q('score-' + score['candidate_id'] + '-' + demo['as_of'])}, {q(score['candidate_id'])}, 'candidate', "
            f"{q(demo['as_of'])}, {score['poll_avg']}, {score['market_prob']}, {score['share_of_voice']}, "
            f"{score['social_attention']}, NULL, {score['composite']}, {j(components)}, {q(score['confidence'])});"
        )

    # 2022 results by department (candidate_id left NULL; party-level baseline for maps)
    for code, department in results["departments"].items():
        for row in department["results"]:
            result_id = f"res-2022-{code}-{row['party_id']}-{row['candidate'].replace(' ', '-').lower()}"
            lines.append(
                "INSERT OR REPLACE INTO results (id, election_id, constituency_id, candidate_id, party_id, votes, pct, source, updated_at) VALUES "
                f"({q(result_id)}, 'pres-2022-t1', {q('dep-' + code)}, NULL, {q(row['party_id'])}, "
                f"{row['votes']}, {row['pct']}, 'Ministere de l Interieur', '2026-11-10T00:00:00Z');"
            )

    # X budget row
    lines.append(
        "INSERT OR IGNORE INTO x_budget (month, reads, cap, updated_at) VALUES "
        f"({q('2026-11')}, 0, 4000, '2026-11-10T00:00:00Z');"
    )

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} statements)")


if __name__ == "__main__":
    main()
